/** The backend derives exactly three levels from `availableStock` vs `safetyStock`. */
export type StockLevel = 'normal' | 'low' | 'out'

export interface InventoryItem {
  id: string
  skuId: string
  warehouseId: string
  locationCode?: string
  totalStock: number
  availableStock: number
  lockedStock: number
  damagedStock: number
  safetyStock: number
  maxStock?: number
  averageCost?: number
  status: StockLevel
  lastInboundAt?: string
  lastOutboundAt?: string
  updatedAt: string
}

/**
 * A warning row from `inv_alert`: unresolved low-stock / out-of-stock alerts are
 * generated by the backend scan job and can be resolved from the alerts screen.
 */
export interface StockAlert {
  id: string
  skuId: string
  warehouseId: string
  locationCode?: string
  currentStock: number
  threshold: number
  status: Extract<StockLevel, 'low' | 'out'>
  alertType?: number
  createdAt?: string
}

export interface InventorySearchParams {
  current?: number
  pageSize?: number
  /** Exact SKU ids — the query API has no name/barcode keyword search. */
  skuIds?: string[]
  warehouseIds?: string[]
  locationCode?: string
  status?: StockLevel
  sortBy?: 'available_stock' | 'total_stock' | 'update_time'
  sortOrder?: 'ASC' | 'DESC'
}

export interface StockAdjustment {
  skuId: string
  warehouseId: string
  quantity: number
  adjustType: 1 | 2 | 6 | 7
  remark?: string
}

export interface PageResult<T> {
  records: T[]
  total: number
  current: number
  pageSize: number
}

/** `ReservationStatus` in the inventory batch 1 state machine (DB only, no REST list yet). */
export type ReservationStatusValue =
  | 'RESERVED'
  | 'CONFIRMED'
  | 'RELEASED'
  | 'EXPIRED'

export interface ReservationRecord {
  businessKey: string
  skuId?: string
  warehouseId?: string
  quantity: number
  status: ReservationStatusValue
  reservedAt?: string
  /** Demo rows cannot be operated; real rows come from a business-key lookup. */
  demo?: boolean
}

export interface ReservationLookupResult {
  businessKey: string
  /** `check` answers true only while the reservation is RESERVED. */
  exists: boolean
  /** `quantity` answers null once the reservation left RESERVED. */
  quantity: number | null
}

export type StockMovementType =
  | 'INBOUND'
  | 'OUTBOUND'
  | 'ADJUST'
  | 'TRANSFER_OUT'
  | 'TRANSFER_IN'
  | 'RESERVE'
  | 'RELEASE'

export interface StockMovement {
  id: string
  skuId: string
  warehouseId: string
  type: StockMovementType
  quantity: number
  availableBefore: number
  availableAfter: number
  referenceNo?: string
  operator?: string
  occurredAt: string
}

