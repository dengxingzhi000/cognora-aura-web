import { v4 as uuidv4 } from 'uuid'

import { inventoryApiService } from '@/lib/api/services/inventory'
import {
  toInventoryItem,
  toInventoryPage,
  toStockAlertsFromAlerts,
  toStockStatus,
} from '../lib/mappers'
import type {
  InventoryItem,
  InventorySearchParams,
  PageResult,
  ReservationLookupResult,
  StockAdjustment,
  StockAlert,
} from '../types'

const ALERT_PAGE_SIZE = 200

export const inventoryService = {
  list: async (params?: InventorySearchParams): Promise<PageResult<InventoryItem>> =>
    toInventoryPage(
      await inventoryApiService.query({
        page: params?.current ?? 1,
        size: params?.pageSize ?? 20,
        skuIds: params?.skuIds?.length ? params.skuIds : undefined,
        warehouseIds: params?.warehouseIds?.length ? params.warehouseIds : undefined,
        locationCode: params?.locationCode || undefined,
        stockStatus: toStockStatus(params?.status),
        sortBy: params?.sortBy ?? 'update_time',
        sortOrder: params?.sortOrder ?? 'DESC',
      })
    ),

  /** Unresolved alerts generated by the backend scan job. */
  getAlerts: async (): Promise<StockAlert[]> => {
    const page = await inventoryApiService.queryAlerts({
      isResolved: false,
      page: 1,
      size: ALERT_PAGE_SIZE,
    });
    return toStockAlertsFromAlerts(page?.records ?? []);
  },

  getStock: (skuId: string, warehouseId: string) =>
    inventoryApiService.getInventory(skuId, warehouseId).then((dto) => (dto ? toInventoryItem(dto) : null)),

  /** `referenceNo` is the server-side 24h idempotency key, so every submission gets its own. */
  adjustStock: async (adjustment: StockAdjustment): Promise<InventoryItem> =>
    toInventoryItem(
      await inventoryApiService.adjust({
        skuId: adjustment.skuId,
        warehouseId: adjustment.warehouseId,
        quantity: adjustment.quantity,
        adjustType: adjustment.adjustType,
        referenceNo: uuidv4(),
        remark: adjustment.remark,
      })
    ),

  transfer: (request: {
    skuId: string;
    fromWarehouseId: string;
    toWarehouseId: string;
    quantity: number;
    remark?: string;
  }) =>
    inventoryApiService.transfer({
      ...request,
      transferNo: uuidv4(),
    }),

  initStock: (skuId: string, warehouseId: string, initialStock: number) =>
    inventoryApiService.initStock(skuId, warehouseId, initialStock),

  /**
   * 后端提供 `check` 与 `quantity` 两个真实接口，但没有预占列表/状态查询接口。
   * `check` 仅在 RESERVED 状态返回 true，`quantity` 在确认/释放/过期后返回 null，
   * 因此这里只能区分“仍预占”和“不在 RESERVED”，无法区分终态是哪一种。
   * 列表接口待后端上线（不得伪造路径）。
   */
  lookupReservation: async (businessKey: string): Promise<ReservationLookupResult> => {
    const [exists, quantity] = await Promise.all([
      inventoryApiService.reservationExists(businessKey),
      inventoryApiService.reservationQuantity(businessKey).catch(() => null),
    ]);
    return {
      businessKey,
      exists: Boolean(exists),
      quantity: typeof quantity === 'number' ? quantity : null,
    };
  },

  confirmReservation: (businessKey: string) =>
    inventoryApiService.confirmReservation(businessKey),

  releaseReservation: (businessKey: string) =>
    inventoryApiService.releaseReservation(businessKey),

  releaseExpiredReservations: () => inventoryApiService.releaseExpired(),

  stats: () => inventoryApiService.stats(),
};
